function importarVarios(i) {
  const txt = document.getElementById(`colar-txt-${i}`).value;
  const novos = txt.split('\n').map(l => l.trim()).filter(l => l.length > 0);
  if (!novos.length) return;
  // Remove entradas vazias antes de adicionar
  albums[i].midias = albums[i].midias.filter(m => m.trim() !== '');
  albums[i].midias.push(...novos);
  salvar('cr_albums', albums);
  renderPainelAlbums();
  renderAlbums();
}

