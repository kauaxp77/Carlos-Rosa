function exportarDados() {
  const dados = JSON.stringify({
    albums: albums,
    deps: depoimentos,
    contatos: contatos
  }, null, 2);
  // Tenta copiar para área de transferência
  if (navigator.clipboard && navigator.clipboard.writeText) {
    navigator.clipboard.writeText(dados).then(() => {
      alert('✓ Dados copiados! Cole no chat com o Claude para ele atualizar o site.');
    }).catch(() => {
      mostrarTextoExportar(dados);
    });
  } else {
    mostrarTextoExportar(dados);
  }
}

function exportarHTML() {
  // Fecha o painel de edição ANTES de capturar o HTML, para que o arquivo
  // exportado nunca abra na tela de administrador, mesmo que o painel
  // esteja aberto no momento do clique.
  const painelEstavaAberto = document.getElementById('painel-edicao').classList.contains('open');
  document.getElementById('painel-edicao').classList.remove('open');

  // Pega o HTML atual da página (já com o painel fechado)
  const html = document.documentElement.outerHTML;

  // Restaura o painel ao estado anterior na tela atual (não afeta o arquivo já capturado)
  if (painelEstavaAberto) {
    document.getElementById('painel-edicao').classList.add('open');
  }

  // Substitui os DEFAULT_ALBUMS, DEFAULT_DEP e DEFAULT_CONTATOS com os dados atuais
  const albumsJSON   = JSON.stringify(albums, null, 2);
  const depJSON      = JSON.stringify(depoimentos, null, 2);
  const contatosJSON = JSON.stringify(contatos, null, 2);

  let resultado = html
    // Substitui os arrays/objetos default pelos dados atuais no código fonte
    .replace(/const DEFAULT_ALBUMS\s*=\s*\[[\s\S]*?\](?=\s*;)/, 'const DEFAULT_ALBUMS = ' + albumsJSON)
    .replace(/const DEFAULT_DEP\s*=\s*\[[\s\S]*?\](?=\s*;)/, 'const DEFAULT_DEP = ' + depJSON)
    .replace(/const DEFAULT_CONTATOS\s*=\s*\{[\s\S]*?\}(?=\s*;)/, 'const DEFAULT_CONTATOS = ' + contatosJSON)
    // Garantia extra: remove a classe "open" do painel-edicao diretamente na marcação,
    // caso ela tenha ficado fixa no HTML original por algum outro motivo.
    .replace(/(<div\s+id="painel-edicao"\s+class=")open(")/, '$1$2');

  // Atualiza a DATA_VERSION para hoje, forçando o site novo a usar os dados embutidos
  const hoje = new Date().toISOString().slice(0,10);
  resultado = resultado.replace(
    /const DATA_VERSION\s*=\s*"[^"]*"/,
    `const DATA_VERSION = "${hoje}"`
  );

  // Cria e dispara o download
  const blob = new Blob([resultado], { type: 'text/html;charset=utf-8' });
  const a = document.createElement('a');
  a.href = URL.createObjectURL(blob);
  a.download = 'carlos-rosa-portfolio.html';
  document.body.appendChild(a);
  a.click();
  setTimeout(() => { document.body.removeChild(a); URL.revokeObjectURL(a.href); }, 500);

  // Feedback visual
  const btn = document.querySelector('[onclick="exportarHTML()"]');
  const orig = btn.textContent;
  btn.textContent = '✓ Baixando…';
  btn.style.background = '#2a7a50';
  setTimeout(() => { btn.textContent = orig; btn.style.background = 'var(--blue)'; }, 2000);
}

